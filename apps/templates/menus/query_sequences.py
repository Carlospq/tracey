def get_keys_recursively(d, keys=None):
	"""
	Recursively gets all keys in a nested dictionary.

	Args:
		d (dict): The dictionary to search.
		keys (list, optional): The list of keys. Defaults to None.

	Returns:
		list: A list of keys.
	"""
	if keys is None:
		keys = []
	for k, v in d.items():
		keys.append(k)
		if v:
			get_keys_recursively(v, keys)
	return keys


def get_keys_level_recursively(d, level=0, keys=None):
	"""
	Recursively gets all keys and returns them as indented menu according to its level.

	Args:
		d (dict): The dictionary to search.
		level (int): indentation level.
		keys (list, optional): The list of keys. Defaults to None.

	Returns:
		list: A list of keys.
	"""
	if keys is None:
		keys = []
	for k, v in d.items():
		keys.append("-"*level + k)
		if v:
			get_keys_level_recursively(v, level+1, keys)
	return keys


def get_dict(dg, d=None):
	"""
	Recursively builds a nested dictionary representing the hierarchy of domain groups.
	Args:
        dg (Domaingroups): The current domain group object.
        d (dict, optional): The dictionary to populate. Defaults to None.

    Returns:
        dict: A nested dictionary representing the domain group hierarchy.
    """
	if d is None:
		d = {}
	d[dg.domaingroupname] = {}
	for dg2 in Domaingroups.objects.filter(domaingroupparent_id=dg.domaingroup_id):
		get_dict(dg2, d[dg.domaingroupname])
	return d


